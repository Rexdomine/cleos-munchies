// Inlines the built admin UI (dist-admin/) into one HTML string and writes it to
// worker/src/generated/adminPage.js, along with the CSP hash of the inline script.
import { createHash } from 'node:crypto';
import { mkdir, readFile, writeFile } from 'node:fs/promises';

const distDir = new URL('../dist-admin/', import.meta.url);
let html = await readFile(new URL('index.html', distDir), 'utf8');
const scriptHashes = [];

html = html.replace(/<link rel="stylesheet"[^>]*href="\/([^"]+)"[^>]*>/g, (_match, file) => `__STYLE__${file}__`);
html = html.replace(/<script type="module"[^>]*src="\/([^"]+)"[^>]*><\/script>/g, (_match, file) => `__SCRIPT__${file}__`);

for (const [, file] of html.matchAll(/__STYLE__(.+?)__/g)) {
  const css = await readFile(new URL(file, distDir), 'utf8');
  html = html.replace(`__STYLE__${file}__`, () => `<style>${css}</style>`);
}
for (const [, file] of html.matchAll(/__SCRIPT__(.+?)__/g)) {
  // Escape "</script" inside the bundle so it cannot end the inline tag early.
  const js = (await readFile(new URL(file, distDir), 'utf8')).replace(/<\/script/gi, '<\\/script');
  scriptHashes.push(`sha256-${createHash('sha256').update(js).digest('base64')}`);
  // Move scripts to the end of <body> so #root exists when they run.
  html = html.replace(`__SCRIPT__${file}__`, '');
  html = html.replace('</body>', () => `<script type="module">${js}</script></body>`);
}

if (!scriptHashes.length) throw new Error('No admin script found in dist-admin/index.html');
const outDir = new URL('../worker/src/generated/', import.meta.url);
await mkdir(outDir, { recursive: true });
await writeFile(
  new URL('adminPage.js', outDir),
  `// Generated by scripts/inline-admin.mjs. Do not edit.\nexport const ADMIN_HTML = ${JSON.stringify(html)};\nexport const ADMIN_SCRIPT_HASHES = ${JSON.stringify(scriptHashes)};\n`,
);
console.log(`Admin page inlined (${Math.round(html.length / 1024)} KB, ${scriptHashes.length} script).`);
