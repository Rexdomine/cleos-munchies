// Generates worker/migrations/0002_seed_menu.sql from src/data/menu.js, so the D1 menu
// starts out identical to the menu the site has shipped with.
import { writeFile } from 'node:fs/promises';
import { CATEGORY_NOTES, MENU, MENU_CATEGORIES } from '../src/data/menu.js';

const sql = (value) => (value === null || value === undefined ? 'NULL' : typeof value === 'number' ? String(value) : `'${String(value).replaceAll("'", "''")}'`);

const lines = ['-- Generated by scripts/generate-menu-seed.mjs. Do not edit by hand.'];
MENU_CATEGORIES.forEach((name, index) => {
  lines.push(`INSERT INTO categories (name, note, sort_order) VALUES (${sql(name)}, ${sql(CATEGORY_NOTES[name] ?? '')}, ${index});`);
});
MENU.forEach((item, index) => {
  lines.push(
    `INSERT INTO menu_items (id, category, name, note, price, image, available, sort_order) VALUES (${[item.id, item.category, item.name, item.note ?? '', item.variants ? null : item.price, item.image, 1, index].map(sql).join(', ')});`,
  );
  (item.variants ?? []).forEach((variant, variantIndex) => {
    lines.push(`INSERT INTO menu_variants (item_id, id, label, price, sort_order) VALUES (${[item.id, variant.id, variant.label, variant.price, variantIndex].map(sql).join(', ')});`);
  });
});

const target = new URL('../worker/migrations/0002_seed_menu.sql', import.meta.url);
await writeFile(target, `${lines.join('\n')}\n`);
console.log(`Wrote ${MENU.length} items and ${MENU_CATEGORIES.length} categories to ${target.pathname}`);
